import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;

public class Solution {
    public static void main(String[] args) throws Exception {
        // Формируем относительный путь 'reports/2024/march' от текущей рабочей директории
        Path reportsPath = Paths.get("reports/2024/march");

        // Создаем все недостающие директории одним методом.
        // Если часть пути уже существует — исключения не будет.
        Files.createDirectories(reportsPath);


        // Выводим абсолютный путь к созданной (или уже существующей) папке 'march'
        System.out.println(reportsPath.toAbsolutePath());

    }
}
