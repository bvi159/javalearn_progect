import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;

public class Solution {
    public static void main(String[] args) {
        // Создаем объект пути, указывающий на "example" относительно текущей директории
        Path whatIsIt = Paths.get("example");
        // Проверяем существование объекта по пути
        try {
            if (Files.isRegularFile(whatIsIt)) {
                System.out.println("Это файл");
            } else if (Files.isDirectory(whatIsIt)) {
                System.out.println("Это папка");
            } else {
                System.out.println("Не найдено");
            }

        } catch (Exception e) {
            throw new RuntimeException(e);
        }

    }
}
