import java.util.Arrays;
import java.util.List;
import java.util.Locale;
import java.util.Objects;

public class Solution {
    public static void main(String[] args) {
        // Исходный список сообщений: среди них есть null и пустые строки
        String[] messages = {
                "Привет", null, "",
                "Как дела?",
                "java", "",
                "Полёт нормальный или около того",
                null
        };

        // Последовательная обработка через Stream:
        Arrays.stream(messages)
                .filter(s -> s != null && !s.isEmpty())
                .map(String::toUpperCase)
                .forEach(System.out::println);
        // Выводим очищенные и отформатированные сообщения на экран (по одному в строке)


    }
}
