import java.io.FileInputStream;
import java.io.IOException;

public class Solution {
    public static void main(String[] args) throws IOException {
        // Имя бинарного файла с артефактом
        String fileName = "энергетический_артефакт.bin";

        // Сумма значений всех байтов (long, чтобы не переполнить int при больших файлах)
        long sum = 0;
        try (FileInputStream inpStrm = new FileInputStream(fileName)) {
            int b;
            while ((b = inpStrm.read()) != -1) {
                // b — это число от 0 до 255 (байт), -1 означает конец файла
                // Можно обработать байт, например, посчитать сумму всех байтов
                sum += b;
            }
        }


        // Если файл пустой, сумма останется 0 — это и есть "энергетический потенциал 0"
        System.out.println(sum);
    }
}
