package ru.javarush.java.core.level48.task07;
/*
Программирование вежливого робота-приветствователя 🤖
Вы — инженер, создающий новую модель робота-приветствователя. Этот робот должен быть умным: вы должны иметь возможность сказать ему, кого приветствовать, и он "запомнит" это имя, чтобы произнести приветствие позже, когда получит команду "говорить".

Ваша задача — реализовать специальный метод public static Runnable greeter(String name). Этот метод не должен сразу произносить приветствие. Вместо этого он должен "подготовить" его, возвращая особую "инструкцию" (лямбда-выражение типа Runnable), которая будет помнить имя и, когда её запустят, выведет на экран "Привет, " + запомненное имя. В основной части вашей программы (main методе) вызовите этот greeter для имени "Анна", сохраните полученную инструкцию и затем дайте ей команду run(). В результате ваш робот должен вежливо поприветствовать: Привет, Анна.

Требования:
•	Необходимо реализовать метод public static Runnable greeter(String name).
•	Метод greeter должен возвращать объект типа Runnable, реализованный с помощью лямбда-выражения.
•	Лямбда-выражение, возвращаемое greeter, должно "запоминать" значение параметра name, переданного при вызове greeter.
•	Лямбда-выражение не должно выполнять приветствие сразу; оно должно делать это только при вызове run().
•	При вызове метода run() у возвращённого Runnable должно быть выведено на экран "Привет, " + имя, переданное в greeter.
•	В методе main необходимо вызвать greeter("Анна"), сохранить результат в переменную, а затем вызвать у неё метод run().
•	В результате выполнения программы на экране должно появиться сообщение: Привет, Анна.
 */
public class Solution {
    // Метод greeter возвращает "инструкцию" (лямбду), которая запоминает имя
    // и позже, при вызове run(), выводит приветствие.
    public static Runnable greeter(String name) {
        // Лямбда захватывает значение параметра name (замыкание)
        return ()-> System.out.println("Привет, " + name);

    }

    public static void main(String[] args) {
        // Готовим приветствие для "Анна", но пока не печатаем — только создаём задачу
        Runnable r = greeter("Анна");

       // Выполняем подготовленную задачу: теперь прозвучит приветствие
        r.run();

    }
}
