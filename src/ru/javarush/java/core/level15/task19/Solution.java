public class Solution {
    public static void main(String[] args) {
        // Создаем два объекта, чтобы увидеть порядок инициализации:
        // 1) При первом создании класса выполняются статические блоки (один раз),
        // 2) Затем для каждого объекта — оба нестатических блока в порядке объявления,
        // 3) После — конструктор.
        new SystemComponent();
        new SystemComponent();
    }
}

class SystemComponent {
    static{
        System.out.println("Глобальная инициализация: Шаг 1");
    }
    static{
        System.out.println("Глобальная инициализация: Шаг 2");
    }
    {
        System.out.println("Инициализация компонента: Шаг А");
    }
    {
        System.out.println("Инициализация компонента: Шаг Б");
    }

    public SystemComponent() {
        System.out.println("Компонент полностью настроен и готов!");
    }
}

