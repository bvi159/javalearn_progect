public class Solution {
    public static void main(String[] args) {
        // Создаем документ с произвольным текстовым содержимым
        Printable doc = new Document("Привет из record-класса!");

        // начало моё изобретение проверяю, как из интерфейса создать экземпляр класса
        Printable newDoc = new Printable() {
            @Override
            public void print() {
                System.out.println("Чего-то печатаем из класса интерфейса");
            }
        };
        newDoc.print();
        //конец моё изобретение проверяю, как из интерфейса создать экземпляр класса

        // Демонстрация работы: печать содержимого документа
        doc.print();

    }
}

interface Printable {
    void print();
}

record Document(String docField) implements Printable {
    @Override
    public void print() {
        System.out.println("Документ: "+ docField());
    }
}

