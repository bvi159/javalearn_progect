import java.util.Scanner;

public class Solution {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int pinCode;

        do {
            System.out.print("Введите PIN-код (четырехзначное число от 1000 до 9999): ");

            // Проверяем, является ли ввод числом
            while (!scanner.hasNextInt()) {
                System.out.print("Ошибка! Введите четырёхзначное число: ");
                scanner.next(); // Очищаем некорректный ввод
            }

            pinCode = scanner.nextInt();

            // Проверяем, является ли число четырехзначным и положительным
            if (pinCode < 1000 || pinCode > 9999) {
                System.out.println("PIN-код должен быть четырёхзначным числом (от 1000 до 9999).");
            }

        } while (pinCode < 1000 || pinCode > 9999);

        System.out.println("PIN-код принят");
        scanner.close();
    }
}

