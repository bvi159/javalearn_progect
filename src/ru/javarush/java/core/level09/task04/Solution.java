public class Solution {
    public static void main(String[] args) {
        // Используем Unicode-последовательности:
        // ☀️ = U+2600 + U+FE0F
        String sun = "\u2600\uFE0F";

        // 😊 = U+1F60A (требует суррогатную пару)
        String smile = "\uD83D\uDE0A";

        System.out.println("Привет, мир! " + sun + smile);
        System.out.println("Привет, мир! \u2600 \uD83D\uDE0A");
        // Просто выводим строку с описанием, а не сам символ
        System.out.println("Символ U+1F60A (улыбающееся лицо)");
        System.out.println("Его суррогатная пара: \\uD83D\\uDE0A");

    }
}