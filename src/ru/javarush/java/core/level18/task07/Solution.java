public class Solution {
    public static void main(String[] args) {
        // Создаем объект робота-приветствия
        Greetings robot = new Greetings();

        // Приветствие по имени
        robot.sayHello("Алекс");

        // Полное приветствие по имени и фамилии
        robot.sayHello("Джон", "Доу");
    }
}

class Greetings {
    void sayHello(String guestName) {
        System.out.println("Hello, " + guestName + "!");
    }

    void sayHello(String guestName, String guestSerName) {
        System.out.println("Hello, " + guestName + " " + guestSerName + "!");
    }

}

