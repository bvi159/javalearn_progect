import java.util.ArrayList;
import java.util.List;

public class Solution {
    public static void main(String[] args) {
        // Создаем динамический список для хранения имен гостей
        ArrayList<String> myGuests = new ArrayList<>(List.of( "Анна", "Иван", "Петр", "Мария"));

        // Добавляем имена в список


        // Проверяем, содержится ли имя "Петр" в списке
        Boolean isPeter = myGuests.contains("Петр");
        System.out.println(isPeter);

        // Проверяем, содержится ли имя "Сергей" в списке
        isPeter = myGuests.contains("Сергей");
        System.out.println(isPeter);

    }
}
