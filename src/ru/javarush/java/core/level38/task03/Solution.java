import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;

public class Solution {
    public static void main(String[] args) {
        // Создаем объект Path, указывающий на директорию "data" в текущей (рабочей) директории
        Path dataPath = Paths.get("data");

        // Проверяем, что путь существует и это именно директория (а не файл)
        if (Files.exists(dataPath) && Files.isDirectory(dataPath)) {
            System.out.println("Папка найдена");
        } else {
            System.out.println("Папка не найдена");
        }


        // Выводим результат проверки

    }
}
