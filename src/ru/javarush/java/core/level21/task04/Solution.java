//import java.util.function.IntFunction;

//@FunctionalInterface
interface IntFunction<R> {
    R apply(int value); // ⬅️ ДОЛЖЕН вернуть объект типа R
}

public class Solution {
    public static void main(String[] args) {
        // Фиксированный префикс для всех отчётных строк
        final String prefix = "Результат: ";

        // Лямбда-выражение — "функция форматирования":
        IntFunction<String> sForm = (a) -> prefix + a*2;

        // Вызов функции с аргументом 7 и вывод результата
        System.out.println(sForm.apply(7));
    }
}
