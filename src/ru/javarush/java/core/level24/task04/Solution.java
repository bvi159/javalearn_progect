/*
Робот-библиотекарь и его "планы спасения"

Вы пишете код для робота-библиотекаря, которому поручено найти очень важный отчёт. Робот должен быть готов к любым "препятствиям": отчёта может не быть на месте, могут возникнуть общие проблемы с доступом к данным, или же произойдёт совсем уж непредвиденная ситуация.
Ваша задача — написать программу, где в основном "рабочем" блоке (try) происходит попытка найти этот отчёт, что симулируется выбрасыванием исключения типа FileNotFoundException — "Отчёт не найден!".
Чтобы робот знал, как реагировать на разные типы "препятствий", предусмотрите три разных "плана спасения" (catch-блока):

Первый план сработает, если "Отчёт не найден" (FileNotFoundException).
Второй план — если возникнут "Общие проблемы с доступом к данным" (IOException), которые более широкие, чем просто отсутствие файла.
И, наконец, третий план — на случай любой "Непредвиденной ситуации" (Exception).
В каждом "плане спасения" выведите на экран сообщение, которое чётко укажет, какой именно из них был активирован. Запустите программу и понаблюдайте, какой из планов робот выберет, чтобы справиться с отсутствующим отчётом.

Требования:
•	В блоке try должно быть выброшено исключение типа FileNotFoundException с сообщением "Отчёт не найден!".
•	В программе должен быть catch-блок, который обрабатывает исключение FileNotFoundException и выводит на экран уникальное сообщение, соответствующее этому плану спасения.
•	В программе должен быть отдельный catch-блок для обработки исключений типа IOException (более широкого класса), с выводом уникального сообщения, указывающего на этот план спасения.
•	В программе должен быть отдельный catch-блок для обработки всех остальных исключений типа Exception, с выводом уникального сообщения, соответствующего этому плану спасения.
•	Catch-блоки должны быть расположены в правильном порядке — от наиболее специфичного (FileNotFoundException) к самому общему (Exception), чтобы не возникало unreachable code.
•	В каждом catch-блоке должно быть чёткое и различимое сообщение, позволяющее определить, какой из планов сработал.

 */

import java.io.*;
import java.nio.file.Files;
import java.nio.file.Path;

public class Solution {
    public static void main(String[] args) {
        try {
            // Имитация поиска отчёта: намеренно бросаем исключение
            Path path = Path.of("c:\\configuration.ini");
            if(!Files.exists(path)){
                throw new FileNotFoundException("Отчёт не найден!");
            };
        } catch (FileNotFoundException e) {
            // Самый специфичный план: файл отсутствует
            System.out.println(e.getMessage());

        } catch (IOException e) {
            // Более общий план: проблемы ввода-вывода
            System.out.println("Ошибка ввода-вывода: " + e.getMessage());

        } catch (Exception e) {
            // Самый общий план: любая другая непредвиденная ситуация
            System.out.println("Непредвиденная ошибка: " + e.getMessage());
            e.printStackTrace();

        }
    }
}

