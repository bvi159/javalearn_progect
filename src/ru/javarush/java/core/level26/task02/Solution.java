import java.util.HashMap;

public class Solution {
    public static void main(String[] args) {
        // Создаем "картотеку" студентов: ключ — имя (String), значение — возраст (Integer)
        HashMap<String, Integer> studentCardBoard =new HashMap<>();
        studentCardBoard.put("Иван", 20);
        studentCardBoard.put("Мария", 21);
        studentCardBoard.put("Алексей", 19);

        // Добавляем три записи о студентах


        // Выводим полный список всех студентов и их возрастов
        System.out.println(studentCardBoard);

    }
}

