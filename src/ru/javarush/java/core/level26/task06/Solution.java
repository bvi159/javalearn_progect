import java.util.Map;
import java.util.TreeMap;

public class Solution {
    public static void main(String[] args) {
        // TreeMap автоматически поддерживает сортировку ключей по алфавиту (естественный порядок String)
        Map<String, Integer> myFuits = new TreeMap<>();
        myFuits.put("pear", 6);
        myFuits.put("apple", 2);
        myFuits.put("banana", 4);
        // Добавляем данные о фруктах
        for (var fruit : myFuits.entrySet()) {
            System.out.println("Фрукт: " + fruit.getKey()+", Количество: " + fruit.getValue());
        }

        // Проходим по записям: порядок уже алфавитный благодаря TreeMap

    }
}


