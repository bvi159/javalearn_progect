import java.io.FileInputStream;
import java.io.IOException;

public class Solution {
    public static void main(String[] args) {
        // Подсчёт общего количества байт
        int byteCount = 0;

        // Открываем файл для чтения с помощью FileInputStream
        // try-with-resources гарантирует закрытие потока даже при исключениях

        long begin = 0;
        long end = 0;
        try (FileInputStream inFile = new FileInputStream("input.txt")) {
            int b;
            begin = System.currentTimeMillis();
            while ((b = inFile.read()) != -1) {
                // Просто читаем, ничего не делаем
                byteCount++;
            }
            end = System.currentTimeMillis();

        } catch (IOException e) {
            System.out.println("Ошибка " + e.getClass().getName());
        }

        // Выводим результат в требуемом формате
        System.out.println("Прочитано байт: " + byteCount);
        System.out.println("Время чтения: " + (end - begin) + " мс");

    }
}
