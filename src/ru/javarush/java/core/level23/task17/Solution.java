package ru.javarush.java.core.level23.task17;
/*
Наводим порядок в запущенном коде 🧹

Представьте, что вы столкнулись с куском "спагетти-кода" в старой, давно не обновлявшейся системе: if(x>0){System.out.println("Положительное");}else{System.out.println("Не положительное");}. Этот код работает, но выглядит как запутанный клубок.
Ваша задача — навести порядок и сделать его легко читаемым, как будто его написал аккуратный и опытный разработчик. Объявите целочисленную переменную inputNumber и присвойте ей любое значение.
Затем перепишите вышеупомянутый логический блок, который проверяет, является ли число положительным. Используйте стандартные отступы, расположите открывающие и закрывающие фигурные скобки на отдельных строках там, где это уместно, чтобы каждая часть условия была четко видна. Сделайте его приятным для глаз и соответствующим общепринятым стандартам форматирования в Java.

Требования:
•	В коде должна быть объявлена переменная с именем inputNumber типа int, которой присваивается некоторое значение.
•	Вся структура кода должна содержать стандартные отступы (обычно 4 пробела на уровень вложенности), чтобы код был легко читаемым.
•	Открывающая фигурная скобка должна находиться на той же строке, что и ключевое слово if или else, а закрывающая — на отдельной строке, согласно Java Code Conventions.
•	Каждая команда (например, вызов System.out.println) должна быть размещена на отдельной строке, чтобы повысить читаемость и упростить восприятие кода.
•	Блок if-else должен быть оформлен так, чтобы логика проверки и действия для каждого случая были отчетливо видны, без слияния кода в одну строку.
 */
public class Solution {
    public static void main(String[] args) {
        // Объявляем целочисленную переменную и присваиваем ей значение
        int inputNumber = 25;
        if (inputNumber > 0) {
            System.out.println("Положительное");
        } else {
            System.out.println("Не положительное");
        }

        // Аккуратно оформленный блок if-else: проверяем, положительное ли число

    }
}

